"""Ports (Protocols) implemented by the I/O adapters."""

from collections.abc import Callable
from pathlib import Path
from typing import Any, Protocol


class Clock(Protocol):
    def now(self) -> float: ...


class StateStore(Protocol):
    def load_session(self, session_id: str) -> dict[str, Any] | None: ...
    def save_session(self, session_id: str, state: dict[str, Any]) -> bool: ...
    def load_published(self) -> dict[str, Any] | None: ...
    def save_published(self, state: dict[str, Any]) -> bool: ...
    def prune(self, now: float) -> int: ...


class TailResult(Protocol):
    objects: list[Any]
    undecodable: int
    position: dict[str, int]
    failed: bool


class Tailer(Protocol):
    def read(self, path: Path, position: dict[str, int] | None) -> TailResult: ...


class HerdrError(Exception):
    """Any failure talking to Herdr (spawn, timeout, protocol, bad input)."""


class HerdrPort(Protocol):
    def list_panes(self) -> list[dict[str, Any]]: ...
    def report(self, pane_id: str, source: str, token: str, value: str, seq: int, ttl_ms: int) -> None: ...
    def clear(self, pane_id: str, source: str, token: str, seq: int) -> None: ...


class HostPlatform(Protocol):
    """OS-specific lifecycle primitives: lock, identity, spawn, stop, signals."""

    supports_socket: bool
    stop_poll_s: float | None  # None: signals wake the loop

    def acquire_lock(self, d: Path) -> object | None: ...  # non-blocking
    def record_identity(self, handle: object, pid: int) -> None: ...
    def release(self, handle: object) -> None: ...  # wipe identity, unlock, close
    def held(self, d: Path) -> bool: ...  # probe; a winner wipes stale identity
    def holder_pid(self, d: Path) -> int | None: ...
    def spawn(self, argv_tail: list[str]) -> None: ...
    def request_stop(self, d: Path, verified_pid: int | None) -> None: ...
    def stop_requested(self, d: Path) -> bool: ...
    def clear_stop(self, d: Path) -> None: ...
    def force_terminate(self, d: Path) -> bool: ...
    def install_signal_handlers(self, on_stop: Callable[[], None]) -> None: ...
